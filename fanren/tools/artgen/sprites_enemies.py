def _orb_frame(orb: Orb, t: int, mode: str) -> Image.Image:
    """画一帧光球。mode: idle（t=0..3 脉动）/ hurt（压扁、偏白）/ down（散成碎光）。

    全部按像素中心取样再量化到色阶，不用 PIL 的抗锯齿，保证每台机器同一结果。
    """
    s = orb.size
    img = Image.new("RGBA", (s, s), (0, 0, 0, 0))
    px = img.load()
    cx = cy = (s - 1) / 2.0
    pulse = [0.0, 0.6, 1.0, 0.6][t % 4]
    r0 = orb.radius * (1.0 + 0.10 * pulse)
    if mode == "hurt":
        r0 = orb.radius * 0.9
    ramp = [P.c(n) for n in orb.core]
    halo_c = P.c(orb.core[1])
    for y in range(s):
        for x in range(s):
            dx, dy = x - cx, y - cy
            if mode == "hurt":
                dx *= 0.85
                dy *= 1.25
            d = math.hypot(dx, dy)
            if mode == "down":
                # 散：外圈碎成点，芯子缩小变淡
                r_core = orb.radius * 0.45
                if d <= r_core:
                    k = d / r_core
                    col = ramp[3] if k < 0.4 else ramp[2]
                    px[x, y] = col + (200,)
                    continue
                ang = math.atan2(dy, dx)
                ring = orb.radius * 1.2
                if abs(d - ring) < 1.0 and (int((ang + math.pi) / (2 * math.pi) * 16) % 3 == 0):
                    px[x, y] = ramp[1] + (170,)
                continue
            if d <= r0:
                k = d / r0
                if k < 0.35:
                    col = ramp[3]
                elif k < 0.62:
                    col = ramp[2]
                elif k < 0.86:
                    col = ramp[1]
                else:
                    col = ramp[0]
                # 左上受光：芯子往左上偏一格的亮斑
                if math.hypot(dx + r0 * 0.35, dy + r0 * 0.35) < r0 * 0.22:
                    col = P.mix(ramp[3], "paper", 0.5)
                if mode == "hurt":
                    col = P.mix(col, "paper", 0.45)
                px[x, y] = col + (255,)
            elif d <= r0 + 3.0:
                # 光晕：三圈逐级变淡（半透明像素，运行时的辉光再把它晕开）
                band = int(d - r0)
                a = (150, 90, 40)[min(2, band)]
                a = int(a * (0.75 + 0.25 * pulse))
                px[x, y] = halo_c + (a,)
    if mode != "down":
        # 绕行的游丝：几个亮点沿椭圆轨道转，每帧转一格
        wc = P.c(orb.wisp)
        for i in range(orb.wisps):
            ang = orb.phase + i * (2 * math.pi / orb.wisps) + t * (math.pi / 8)
            rx, ry = r0 + 2.5, (r0 + 2.5) * 0.55
            wx = int(round(cx + rx * math.cos(ang)))
            wy = int(round(cy + ry * math.sin(ang)))
            for ddx, ddy, a in ((0, 0, 255), (1, 0, 140), (-1, 0, 140), (0, 1, 110), (0, -1, 110)):
                xx, yy = wx + ddx, wy + ddy
                if 0 <= xx < s and 0 <= yy < s:
                    old = px[xx, yy]
                    if old[3] < a:
                        px[xx, yy] = wc + (a,)
    return img


def render_orb(orb: Orb) -> tuple[Image.Image, dict[str, list[int]]]:
    frames = [_orb_frame(orb, t, "idle") for t in range(4)]
    frames.append(_orb_frame(orb, 0, "hurt"))
    frames.append(_orb_frame(orb, 0, "down"))
    layout = {"idle": [0, 1, 2, 3], "hurt": [4], "down": [5]}
    return grid_sheet(frames, len(frames), orb.size, orb.size), layout
