@dataclass(frozen=True)
class Beast:
    id: str
    name: str
    w: int
    h: int
    idle: tuple[str, ...]
    attack: tuple[str, ...]
    down: tuple[str, ...]
    ramps: dict[str, list[tuple[int, int, int]]]
    codes: dict[str, tuple[str, int]]
    leg_top: int          # 待机呼吸时，这一行以上整体下沉
    note: str = ""


def _codes(extra: dict[str, tuple[str, int]] | None = None) -> dict[str, tuple[str, int]]:
    base = {
        "A": ("fur", 3), "B": ("fur", 2), "C": ("fur", 1), "D": ("fur", 0),
        "E": ("belly", 3), "F": ("belly", 2), "G": ("belly", 1),
        "e": ("eyeglow", 3), "n": ("ink", 1), "W": ("tooth", 3), "r": ("mouth", 2),
        "k": ("claw", 2),
    }
    if extra:
        base.update(extra)
    return base


