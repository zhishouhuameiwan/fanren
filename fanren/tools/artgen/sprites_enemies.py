def _canvas_from(rows: tuple[str, ...], beast: Beast) -> Canvas:
    c = Canvas(beast.w, beast.h)
    c.stamp(list(rows), 0, 0, beast.codes)
    return c


def _breath(c: Canvas, leg_top: int) -> Canvas:
    """待机第二帧：腿以上整体下沉一格（腿不动，身子压一压）。"""
    out = c.copy()
    for y in range(leg_top - 1, 0, -1):
        out.px[y] = c.px[y - 1][:]
    out.px[0] = [None] * c.w
    # 腿顶那一行保持原样，免得身子与腿之间裂开一道缝
    out.px[leg_top - 1] = [c.px[leg_top - 1][x] or c.px[leg_top - 2][x] for x in range(c.w)]
    return out


def _hurt(c: Canvas) -> Canvas:
    """受击：往后（左）一缩、往上一挺；眼睛闭上（眼光换成暗面）。"""
    out = c.shifted(-2, -1)
    for y in range(out.h):
        for x in range(out.w):
            v = out.px[y][x]
            if v is not None and v[0] == "eyeglow":
                out.px[y][x] = ("ink", 1)
    return out


def render_beast(beast: Beast) -> tuple[Image.Image, dict[str, list[int]]]:
    mats = Materials.build(beast.ramps)
    idle0 = _canvas_from(beast.idle, beast)
    frames = [
        idle0,
        _breath(idle0, beast.leg_top),
        _canvas_from(beast.attack, beast),
        _hurt(idle0),
        _canvas_from(beast.down, beast),
    ]
    imgs = [to_image(add_outline(f, mats), mats) for f in frames]
    layout = {"idle": [0, 1], "attack": [2], "hurt": [3], "down": [4]}
    return grid_sheet(imgs, len(imgs), beast.w, beast.h), layout


