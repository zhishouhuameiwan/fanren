"""粒子贴图：叶、花瓣、火星、雨丝、雪片、尘埃、萤火、火花、破势碎片。

叶与花瓣、碎片是手画的灰度像素模板（运行时乘色：叶乘绿/枯黄、花瓣乘粉、碎片乘玉青或金）；
发光类（火星、萤火、火花、雪、尘）按像素中心的解析式算 alpha。
火星是少数带颜色的一种——火本来就不需要运行时再染。
"""

