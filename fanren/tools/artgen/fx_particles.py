def leaves() -> Image.Image:
    return strip([grey_tpl(t, 8, 8) for t in LEAVES])


def petals() -> Image.Image:
    return strip([grey_tpl(t, 8, 8) for t in PETALS])


def shards() -> Image.Image:
    return strip([grey_tpl(t, 12, 12) for t in SHARDS])


def _dot(size: int, r_core: float, r_halo: float, core_a: float = 255.0, halo_a: float = 150.0,
         color=(255, 255, 255)) -> Image.Image:
    img = Image.new("RGBA", (size, size), color + (0,))
    px = img.load()
    c = size / 2.0
    for y in range(size):
        for x in range(size):
            d = math.hypot(x + 0.5 - c, y + 0.5 - c)
            if d <= r_core:
                a = core_a
            else:
                a = halo_a * (1.0 - smoothstep(r_core, r_halo, d))
            px[x, y] = color + (_q(a),)
    return img


def embers() -> Image.Image:
    """火星：芯子黄白、外圈橙红，四帧明灭。带颜色。"""
    core = P.mix("gold4", "paper", 0.3)
    mid = P.c("gold3")
    edge = P.c("red3")
    frames = []
    for rc, rh in ((1.0, 2.6), (1.5, 3.4), (1.2, 3.0), (0.7, 2.2)):
        img = Image.new("RGBA", (8, 8), (0, 0, 0, 0))
        px = img.load()
        for y in range(8):
            for x in range(8):
                d = math.hypot(x + 0.5 - 4.0, y + 0.5 - 4.0)
                if d <= rc:
                    px[x, y] = core + (255,)
                elif d <= rc + 0.9:
                    px[x, y] = mid + (230,)
                elif d <= rh:
                    t = (d - rc - 0.9) / max(0.01, rh - rc - 0.9)
                    px[x, y] = edge + (_q(170 * (1.0 - t)),)
        frames.append(img)
    return strip(frames)


def rain() -> Image.Image:
    """雨丝：4×16，中间两列从上到下由淡到浓。运行时斜着落。"""
    def a(x: float, y: float) -> float:
        across = 1.0 if 1.0 <= x <= 3.0 else 0.0
        return 190.0 * across * smoothstep(0.0, 1.0, y / 16.0) * (0.55 if x < 2.0 else 1.0)

    img = Image.new("RGBA", (4, 16), (255, 255, 255, 0))
    px = img.load()
    for y in range(16):
        for x in range(4):
            px[x, y] = (255, 255, 255, _q(a(x + 0.5, y + 0.5)))
    return img


def snow() -> Image.Image:
    return strip([_dot(8, 0.8, 1.8, 255, 170), _dot(8, 1.3, 2.6, 255, 150), _dot(8, 1.8, 3.6, 240, 120)])


def dust() -> Image.Image:
    return _dot(4, 0.6, 2.0, 210, 150)


def firefly() -> Image.Image:
    return strip([_dot(8, 1.0, 3.8, 255, 140), _dot(8, 0.6, 2.8, 200, 90)])


def spark() -> Image.Image:
    """火花：四角星，三帧由长到短。"""
    frames = []
    for ray in (3.6, 2.6, 1.4):
        img = Image.new("RGBA", (8, 8), (255, 255, 255, 0))
        px = img.load()
        for y in range(8):
            for x in range(8):
                dx, dy = abs(x + 0.5 - 4.0), abs(y + 0.5 - 4.0)
                a = 0.0
                if dx < 0.6:
                    a = max(a, 255.0 * (1.0 - smoothstep(0.0, ray, dy)))
                if dy < 0.6:
                    a = max(a, 255.0 * (1.0 - smoothstep(0.0, ray, dx)))
                if dx < 1.1 and dy < 1.1:
                    a = max(a, 200.0)
                px[x, y] = (255, 255, 255, _q(a))
        frames.append(img)
    return strip(frames)
