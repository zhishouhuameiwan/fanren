def _arrow_rows(phase: int) -> list[str]:
    """朝上的箭头（地面上压扁的 V 字 ×2），phase 0-2 往前挪一格。"""
    base = [
        "................",
        "................",
        ".......AA.......",
        "......ABBA......",
        ".....AB..BA.....",
        "....AB....BA....",
        "...AB......BA...",
        "................",
        ".......AA.......",
        "......ABBA......",
        ".....AB..BA.....",
        "....AB....BA....",
        "...AB......BA...",
        "................",
        "................",
        "................",
    ]
    rows = ["." * 16] * (2 - phase) + base
    rows = rows[: 16] if len(rows) >= 16 else rows + ["." * 16] * (16 - len(rows))
    return rows


def _rotate(rows: list[str], d: str) -> list[str]:
    n = len(rows)
    if d == "up":
        return rows
    if d == "down":
        return [r for r in reversed(rows)]
    if d == "left":
        return ["".join(rows[y][n - 1 - x] for y in range(n)) for x in range(n)]
    if d == "right":
        return ["".join(rows[n - 1 - y][x] for y in range(n)) for x in range(n)]
    raise ValueError(d)


