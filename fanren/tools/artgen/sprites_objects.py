@dataclass(frozen=True)
class Obj:
    id: str
    name: str
    w: int          # 像素
    h: int
    frames: tuple[tuple[str, ...], ...]
    codes: dict
    fps: float = 0.0
    outline: bool = True
    note: str = ""
    ground_marker: bool = False   # 平铺在格子上的标记（箭头、闪光）：一帧就是一格，锚点取帧底边中点


def F(text: str) -> tuple[str, ...]:
    return tuple(tpl(text))


def pad_top(rows: tuple[str, ...], n: int) -> tuple[str, ...]:
    """在模板上面补 n 行空：物件帧高一律取 16 的倍数（施工要求「以 16px 格为单位」），落地点不变。"""
    w = len(rows[0])
    return tuple(["." * w] * n) + rows


