def _bubble(glyph: list[str], ox: int = 3, oy: int = 2) -> tuple[str, ...]:
    rows = [list(r) for r in tpl(_BUBBLE)]
    for j, line in enumerate(glyph):
        for i, ch in enumerate(line):
            if ch != ".":
                rows[oy + j][ox + i] = ch
    return tuple("".join(r) for r in rows)


