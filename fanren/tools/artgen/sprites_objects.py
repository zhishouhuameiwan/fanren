def _doorlight(rows: tuple[str, ...]) -> Image.Image:
    """门光：门洞里自下而上渐淡的一道光，两侧门框线更亮，几点光尘往上飘。

    rows 里只放帧号（'0'/'1'/'2'），图形由解析式算——渐变用字符模板画不细。
    """
    from fx_textures import hash01, smoothstep

    f = int(rows[0])
    w, h = 16, 32
    img = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    px = img.load()
    col = P.mix("gold4", "paper", 0.5)
    pulse = (1.0, 0.82, 0.92)[f]
    for y in range(h):
        for x in range(w):
            if not (4 <= x <= 11) or y < 3 or y > 27:
                continue
            t = (27.5 - (y + 0.5)) / 24.0            # 0 在门槛 → 1 在门楣
            a = 200.0 * (1.0 - smoothstep(0.0, 1.0, t)) * pulse
            if x in (4, 11):
                a = min(255.0, a * 1.25 + 30.0)
            if y == 27:
                a = 255.0 * pulse
            a = int(round(a / 32.0)) * 32            # 量化成几级，保持像素画的硬
            if a > 0:
                px[x, y] = col + (min(255, a),)
    for i in range(4):
        mx = 5 + int(hash01(i, 0, 61) * 6)
        my = 26 - ((int(hash01(i, 1, 61) * 20) + f * 5) % 22)
        if 3 <= my <= 27:
            px[mx, my] = P.c("paper") + (255,)
    return img


