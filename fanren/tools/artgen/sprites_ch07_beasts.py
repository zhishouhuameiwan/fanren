_ROCK_W, _ROCK_H = 40, 32
# 岩壁的轮廓：每一行左、右边界（含）。上窄下宽、左右不齐，像从石窟顶上垂下来的一块岩层。
_ROCK_SPAN = {
    5: (12, 25), 6: (9, 28), 7: (7, 30), 8: (6, 31), 9: (5, 32), 10: (5, 33), 11: (4, 33), 12: (4, 34),
    13: (4, 34), 14: (3, 34), 15: (3, 35), 16: (3, 35), 17: (3, 35), 18: (3, 35), 19: (3, 36), 20: (2, 36),
    21: (2, 36), 22: (2, 36), 23: (2, 37), 24: (2, 37), 25: (2, 37), 26: (1, 37), 27: (1, 38), 28: (1, 38),
}
_STRATA = (11, 18, 24)                    # 横着的岩层纹
_RUNE_CENTER, _RUNE_R = (19, 17), 6       # 禁制符纹：一圈环、中间一个「封」字的意思（三横一竖）
_CRACKS_IDLE = ((9, 8), (10, 9), (30, 21), (31, 22), (31, 23))
_CRACKS_HURT = _CRACKS_IDLE + (
    (11, 10), (12, 11), (12, 12), (13, 13), (27, 9), (26, 10), (26, 11), (25, 12),
    (30, 20), (29, 19), (28, 19), (6, 22), (7, 23), (7, 24), (8, 25), (24, 25), (23, 26), (23, 27),
)
# 出招时顶上落下的碎石：三块成形的石块（左上角坐标、宽、高），砸向右边的我方
_DEBRIS = ((31, 0, 3, 2), (36, 2, 2, 2), (33, 5, 2, 2))


def _rune_cells(bright: bool) -> dict[tuple[int, int], str]:
    cx, cy = _RUNE_CENTER
    cells: dict[tuple[int, int], str] = {}
    for y in range(cy - _RUNE_R, cy + _RUNE_R + 1):
        for x in range(cx - _RUNE_R, cx + _RUNE_R + 1):
            d2 = (x - cx) ** 2 + (y - cy) ** 2
            if (_RUNE_R - 1) ** 2 <= d2 <= _RUNE_R ** 2:
                cells[(x, y)] = "Z" if bright else "z"
    for dy in (-3, 0, 3):                      # 三横
        for dx in range(-2, 3):
            cells[(cx + dx, cy + dy)] = "Z"
    for dy in range(-3, 4):                    # 一竖
        cells[(cx, cy + dy)] = "Z"
    return cells


def _rock_rows(pose: str) -> tuple[str, ...]:
    grid = [["."] * _ROCK_W for _ in range(_ROCK_H)]
    if pose == "down":
        # 崩开：一堆碎岩趴在地上，几块散开，符纹碎成几点暗金。
        pile = {24: (8, 30), 25: (5, 33), 26: (3, 35), 27: (2, 37), 28: (1, 38)}
        for y, (x0, x1) in pile.items():
            for x in range(x0, x1 + 1):
                grid[y][x] = "B"
            grid[y][x0], grid[y][x1] = "A", "C"
        for x in range(1, 39):
            grid[28][x] = "D" if grid[28][x] != "." else "."
        for (x, y) in ((10, 22), (11, 22), (10, 23), (11, 23), (26, 21), (27, 21), (26, 22), (27, 22), (28, 22),
                       (18, 22), (19, 22), (18, 23)):
            grid[y][x] = "B"
        for (x, y) in ((14, 26), (21, 25), (29, 27)):
            grid[y][x] = "z"
        for (x, y) in ((9, 25), (16, 27), (24, 26), (31, 26)):
            grid[y][x] = "n"
        return tuple("".join(r) for r in grid)
    for y, (x0, x1) in _ROCK_SPAN.items():
        for x in range(x0, x1 + 1):
            grid[y][x] = "B"
        grid[y][x0] = "A"
        if x0 + 1 <= x1:
            grid[y][x0 + 1] = "A" if y < 16 else "B"
        grid[y][x1] = "D"
        if x1 - 1 >= x0:
            grid[y][x1 - 1] = "C"
    for x in range(_ROCK_SPAN[5][0], _ROCK_SPAN[5][1] + 1):
        grid[5][x] = "A"
    for y in _STRATA:
        x0, x1 = _ROCK_SPAN[y]
        for x in range(x0 + 2, x1 - 1):
            if (x * 7 + y) % 5 != 0:             # 断断续续的一道层纹
                grid[y][x] = "C"
    for x in range(_ROCK_SPAN[28][0], _ROCK_SPAN[28][1] + 1):
        grid[28][x] = "D"
    for (x, y), ch in _rune_cells(bright=pose in ("idle2", "attack")).items():
        grid[y][x] = ch
    cracks = _CRACKS_HURT if pose == "hurt" else _CRACKS_IDLE
    for (x, y) in cracks:
        grid[y][x] = "n"
    if pose == "attack":
        for (x0, y0, w, h) in _DEBRIS:         # 顶上落碎石，砸向右边的我方
            for y in range(y0, y0 + h):
                for x in range(x0, x0 + w):
                    grid[y][x] = "A" if y == y0 else "C"
    return tuple("".join(r) for r in grid)


