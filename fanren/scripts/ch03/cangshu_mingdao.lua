-- @hook ch03_cangshu trigger_mingdao enter
-- 第三章节点 6 的另一半：「走明路进藏书处」。
-- 挂在 ch03_cangshu 门口的 trigger（mode=**enter**，**once=false**，可反复撞）。
-- 这一行从前写的是 interact，与地图对不上。enter 与这一节要的东西一致：
-- 他推开门、走进去，廊子那头站着人——这件事不该要玩家先按一次确认键才发生。
-- 口径以首行的 @hook 为准（tools/validate.py 比着 maps/*.tmj 校验）。
--
-- 这个脚本存在的理由只有一个：让「等一场雨」变成玩家自己得出的结论，
-- 而不是一句被告知的规矩。他白天推得开那扇门，推开之后廊子那一头站着人，
-- 于是他自己退出来。设计第 6 节要的「被发现的风险感」落在这里，
-- 落成一次**没有惩罚的碰壁**——玩家没损失什么，可他再也不想白天来了。
--
-- 三条施工限制在这一处同时适用：
--   * once=false，所以脚本自己不置任何完成旗标（置了下回就进不来，
--     反复撞的手感就没了）；
--   * 玩家点了必须有话说，不许静默——所以已经偷完之后也有一条 again；
--   * 它与 miji.lua 分成两个文件，因为一段脚本没法在中途把控制权交还玩家。
--
-- 那个不出声的在这里第二次出现（第一次在节点 2）。同样一个字也不解释：
-- 他没有朝韩立转过来，也没有走开。要到节点 8 暗道那一仗之后，
-- 韩立才会把「两只脚上分量一样重」这件事和它对上。

