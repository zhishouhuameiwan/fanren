--
-- ---------------------------------------------------------------------------
-- 这个脚本是「摊牌前后是同一个人」这条要求最直白的证物，请照此维护。
-- ---------------------------------------------------------------------------
-- 摊牌之前（mo_daifu）：他在灯下写方子，说带回来一味新药要考考徒弟，
--   说人上了年纪写字的手不听使唤。**一句可疑的话也没有**，
--   没有打量、没有意味深长的停顿、没有笑意——第 1、2 章反复要求的那条，
--   到本章摊牌那一刻之前仍然有效。
-- 摊牌之后（mo_juren）：**口吻一个字也没改**。他还是关切韩立气色不好、
--   还是替他把茶盏挪正半寸、还是说那句教了四年的「学医先学不害人」，
--   而且说这句时补了一句「这句话他自己也是信的，信了大半辈子」。
--   变的不是他，是玩家听得懂了。
--
-- 所以这两组台词**不许写成前后判若两人**。谁要改，判据是：
-- 把 after 那三条原样搬到 before 去，玩家不该看出破绽；
-- 搬过去一眼就看得出不对的，就是把人写成了两张脸，重写。
--
-- 脚本无从得知是哪个 NPC 触发了它（施工限制第 2 条），所以密室里若还有别人说话，
-- 各挂各的脚本，不要在这里用旗标去分。

if flag.get("ch03.tanpai_done") ~= 1 then
    talk("mo_daifu", "ch03.npc.mojuren_before_1")
    talk("mo_daifu", "ch03.npc.mojuren_before_2")
    return
end

-- 尸虫丸吞下之后他就不大说话了。这一条要摆在 after 那三条前面：
-- 玩家一旦走完节点 4，回头再找他闲聊，能听到的就越来越少。
if flag.get("ch03.jieyao_xuan") > 0 then
    talk("mo_juren", "ch03.npc.mojuren_again")
    return
end

talk("mo_juren", "ch03.npc.mojuren_after_1")
talk("mo_juren", "ch03.npc.mojuren_after_2")
talk("mo_juren", "ch03.npc.mojuren_after_3")
