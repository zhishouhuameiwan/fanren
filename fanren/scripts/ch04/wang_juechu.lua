-- 他是**七玄门门主**，原著 ch82 原文：「七玄门门主王绝楚，犹如冰人般的冷冷回答道」。
-- 首见 ch82，与金光上人同章登场 —— 也就是说，玩家在节点 8 之前**不该认得他**。
-- 可地图把他常驻在掌门殿上，玩家从节点 1 起就能上来跟他说话。
-- 这一处的解法不是把他藏起来（关卡侧已交付，不改地图），而是让他在节点 8 之前
-- **一个字也不多说**：四条里最靠前的那一条只有三个字「知道了」，连头都不抬。
-- 玩家见得着他，却什么也没得到 —— 这与「他这个人首见于 ch82」在观感上是一回事。
--
-- 语气卡：**冷、短、不解释。** 四条一共没有一句完整的解释性台词。
-- 最要紧的是第三条：他说山下十几处哨卡丢了九处，而那口气和他交代换茶的时辰
-- 一模一样 —— 听不出哪一句更要紧。**不许给他一段动员，也不许让他慌。**
--
-- 第四条是原著 ch97「背后交易」的落地：门里确实有人议过要对韩大夫下手，
-- 他说那几个人已经拿下了，然后看韩立一眼 —— 那一眼里没有歉意，
-- 只是让他知道自己听见了。**不许让他道歉**，也不许让韩立当场发作。
-- 这一条与节点 11 那笔交易连着：韩立正是在这之后才决定提前半日单独见他。
--
-- 分段只用本章已登记的旗标，**不另立**（编剧不得往 data/flags.json 里加旗标）。
