-- 第四章节点 7「贾天龙现身」。
-- 挂在 ch04_shanxiazhen 坊门那两格 (19,17)(20,17) 的 trigger
-- （mode=enter，once=true，guard_flag=ch04.kaizhan，set_flag=ch04.jia_tianlong）。
-- 坊墙横在 y=16，坊门是北街下市集唯一的口子（genmaps_ch04.py make_shanxiazhen）。
-- 他是下山补药材的，药市在坊墙以南那片石板空场上，这一趟非走这两格不可 ——
-- **堵他的人算准了他必走这一趟**，所以摆成踏入型，他没有绕开的余地。
--
-- ---------------------------------------------------------------------------
-- 硬约束 3：贾天龙不是本章凭空冒出来的人，ch38 早有伏笔
-- ---------------------------------------------------------------------------
-- 伏笔的内容不是「他很可怕」，恰恰相反：ch38 里厉飞雨告诉过韩立，
-- 传闻中那个青面獠牙、一天三顿吃人的魔头，实际上又瘦又白净、三十出头。
-- **本节认人靠的就是这条反着的线索**：认出他的不是哪一处像，是处处都不像。
-- 这条线索四年前由一个玩家认识的人亲口给过，不是这一刻才发的提示 ——
-- 第 3 章独立校对点名要求过「回头找得到线索」，这一处是本章的落点。
--
-- ---------------------------------------------------------------------------
-- 取材角度：原著 ch81 整章跟着贾天龙的视角，本作的镜头一步也没有离开韩立
-- ---------------------------------------------------------------------------
-- 所以连弩的来路、中小帮派首领的家小被扣、三千两黄金请人 —— 这些原著在 ch81
-- 里交代得清清楚楚的事，本节一件也没有写。韩立在坊门底下看得见的只有：
-- 四个穿红的在把镇上的伤药收干净，给的钱一块一块数得清楚，卖药的收了钱还在抖。
-- 一个正要开打的人先买光对方的伤药，这件事本身比任何解说都冷。
--
-- ---------------------------------------------------------------------------
-- 二选一：报不报假身份（ch04.jia_tianlong = 1 报假的 / 2 不吭声）
-- ---------------------------------------------------------------------------
-- 两条都会打起来 —— 拆穿他的不是嘴，是药篓里那几包盖着门里朱印的油纸。
-- 分的是**贾天龙手上多了一条什么样的假消息**：报了假的，对方带走一句
-- 「山上那位神医六十三岁」；不吭声，对方带走的是一张仔细看过的脸。
-- 节点 8 金光上人在殿上从头到尾没有单独看韩立一眼，与这一处对照着读：
-- 一个记住了他的脸，一个连看都没看 —— 而要命的是后者。
--
-- 旗标值必须非零：ch04_getang 的 trigger_jinguang 拿它当 guard_flag。
--
-- **贾天龙本人不在编成里。** b04_jia_tianlong 打的是他那四名红衣铁卫，
-- 他背过身去站着，看完就走。让玩家在这一节把他打死与原著 ch94 直接冲突 ——
-- 他要死在节点 9 的最后一波上。理由连同数值写在那份战斗数据的 note 里。
--
-- **这一场可逃可败**（can_escape 真、defeat_is_fatal 假）。输了不是死路：
-- 药篓翻了，他空着手爬回山上。贾天龙叫住手下不是慈悲 —— 一个死人捎不了话，
-- 他要七玄门知道他就在山下。

if flag.get("ch04.jia_tianlong") ~= 0 then
    talk("", "ch04.jia.again")
    return
end

talk("", "ch04.jia.need")
talk("", "ch04.jia.down")
talk("", "ch04.jia.town")
talk("", "ch04.jia.gate")
talk("", "ch04.jia.buy")
talk("", "ch04.jia.pay")
talk("", "ch04.jia.man")
talk("", "ch04.jia.rumor")
talk("", "ch04.jia.feiyu_said")
talk("", "ch04.jia.know")
talk("", "ch04.jia.talk")

local pick = choice{
    "ch04.jia.opt_lie",
    "ch04.jia.opt_silent",
}

if pick == 2 then
    talk("", "ch04.jia.silent1")
    talk("", "ch04.jia.silent2")
else
    -- 报假身份（pick == 1）与取消（pick == nil）走同一条。
    -- 没做选择按报假的算：对方客客气气问了一句，当街杵在那儿不出声，
    -- 对一个刚把半镇伤药买空的人来说反倒是最扎眼的答法，而他不会选最扎眼的那一种。
    talk("", "ch04.jia.lie1")
    talk("", "ch04.jia.lie2")
end

talk("", "ch04.jia.seal")
talk("", "ch04.jia.draw")

local won, how = battle("b04_jia_tianlong")

if won then
    talk("", "ch04.jia.win1")
    talk("", "ch04.jia.win2")
else
    -- 败与逃走同一条：两种都是空着手回去。这一场不会出现 "enemy_fled"
    -- （铁卫不逃），真出现了按没打完算，台词照样说得通。
    talk("", "ch04.jia.lose1")
    talk("", "ch04.jia.lose2")
end

talk("", "ch04.jia.name")
talk("", "ch04.jia.cold")
talk("", "ch04.jia.leave")
talk("", "ch04.jia.back")

flag.set("ch04.jia_tianlong", pick == 2 and 2 or 1)
