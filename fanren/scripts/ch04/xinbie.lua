-- @hook ch01_hanjiacun trigger_xinbie interact once
-- 第四章节点 11 之二「留药与信别厉飞雨」。本章最后一次二选一。
-- 挂在 ch01_hanjiacun 韩家屋南那两格 (12,14)(13,14) 的 trigger
-- （mode=interact，once=true，guard_flag=ch04.hui_cun，set_flag=ch04.xin_neirong）。
-- 韩家的屋子是 (10,10)-(15,13) 那一间（第 1 章旧图，屋檐在北面 y=9），
-- 所以这两格正贴着它的南墙根，是屋后而不是门前 —— 文案照这个写：
-- 「他绕到自家屋后。屋南那面墙晒了一天，还温着。」
-- 生成器注里管这一处叫「韩家屋南的院子」，图上并没有另砌院墙，
-- 所以文案只说墙根与一块青石，**不写院门、不写院墙**
-- （第 3 章 C3-4 那四处「脚本把挂点的地物说错了」的教训）。
--
-- **mode=interact 是设计本身**：这一节是他自己坐下来写的，不该是走着走着撞上的。
--
-- ---------------------------------------------------------------------------
-- 二选一：信里写什么（ch04.xin_neirong = 1 只写药怎么吃 / 2 写一句道别）
-- ---------------------------------------------------------------------------
-- 原著 ch98 那张纸条上有四样：告诉他自己走了、药是精心配过的、
-- 署名处画了一张笑脸、外加一句祝他和张姑娘早日成亲。
-- 本作**一样也不照搬**（复验 N-9：先前第 2 条留着笑脸与「早些办了」，正是那张纸条上的
-- 两样东西；2026-09-23 已整条重写），改成两条**互斥**的写法，让玩家选韩立是哪一种人：
--   1 写满一整张吃法，一句闲话也没有，从头到尾没提自己要走 ——
--     厉飞雨读到最后一行才会明白，而那时他已经在很远的地方了。
--   2 只写两行：「药别省着吃。刀别磨过头。」两句都取自本作自己种下的东西——
--     第 2 章厉飞雨说那药他省着吃、一天一勺，韩立回他省着吃等于没吃（ch02.npc.lifeiyu_yao）；
--     「磨过头就脆」是厉飞雨自己磨刀时的话（ch03.npc.lifeiyu_again）。
--     拿人家的话去嘱咐人家，他觉得有点可笑，写完也没有划掉；两行字底下空着一大片。
-- 两条都不是错的那一种，这一点要紧：第 1 条不是冷漠（它是他唯一会的表达），
-- 第 2 条也不是软弱。
--
-- ---------------------------------------------------------------------------
-- **take() 的返回值在这里是分岔，不是守卫**
-- ---------------------------------------------------------------------------
-- 留下的药是养精丹（原著 ch27 交代过它的功用：内外伤都有奇效，可保住性命；
-- ch98 王绝楚靠的正是这一味）。它由节点 3 教的炼丹炼出来
-- （data/recipes/alchemy/yangjing_dan.json），所以玩家完全可能一瓶也没有 ——
-- 那是他自己这一章没去开炉，或者开了炉没炼成。
--
-- 两条都走得到，而且两条的后果不一样：
--   扣得到三瓶 → 药和信一起裹好托车夫捎回山下；
--   扣不到     → 他翻遍箱底也没有，只好把寻常伤药裹进去，另添半页
--                「这个方子在峰上丹房的柜里，你自己找人配」。
-- **绝不做成「说留了药却什么也没少」**：第 2 章在 take() 上栽过两次，
-- 第二次让玩家白拿了 167 块。
--
-- 可达性：节点 3 无论选哪一条报价，门里发下来的俸禄药材都够炼三炉养精丹
-- （照价 黄精 6 株 24 年 / 紫参 3 株 24 年；只收药钱 黄精 10 株 22 年 / 紫参 4 株 22 年，
-- 方子要黄精 2 株 + 紫参 1 株，都要 20 年以上）。逐条算在交付报告里。

if flag.get("ch04.xin_neirong") ~= 0 then
    talk("", "ch04.xinbie.again")
    return
end

talk("", "ch04.xinbie.yard")
talk("", "ch04.xinbie.sit")
talk("", "ch04.xinbie.think")
talk("", "ch04.xinbie.pills")

-- **看返回值。** 扣不到就一瓶不扣、返回 false，走另一条，绝不静默。
local has_pills = take("pill_yangjing_dan", 3)

if has_pills then
    talk("", "ch04.xinbie.have")
else
    talk("", "ch04.xinbie.none")
end

local pick = choice{
    "ch04.xinbie.opt_plain",
    "ch04.xinbie.opt_bye",
}

if pick == 2 then
    talk("", "ch04.xinbie.bye1")
    talk("", "ch04.xinbie.bye2")
else
    -- 只写吃法（pick == 1）与取消（pick == nil）走同一条。
    -- 没做选择按只写吃法算：他在这张纸前面已经坐了五天没想好，
    -- 而一个想不好怎么道别的人，最后写下来的总是他会写的那一种。
    talk("", "ch04.xinbie.plain1")
    talk("", "ch04.xinbie.plain2")
end

-- 包什么，由上面那次 take 的结果决定 —— 两条包的东西不同，说的话也不同。
if has_pills then
    talk("", "ch04.xinbie.pack_full")
else
    talk("", "ch04.xinbie.pack_bare")
end

talk("", "ch04.xinbie.driver")
talk("", "ch04.xinbie.end")

flag.set("ch04.xin_neirong", pick == 2 and 2 or 1)
