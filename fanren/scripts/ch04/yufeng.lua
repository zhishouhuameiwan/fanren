-- 它不在峰上任何一条必经的路上，所以摆成 interact：玩家要自己拐过去、面朝它按确认。
--
-- ---------------------------------------------------------------------------
-- 硬约束 1 的后半：火弹术在先，御风决在后，**中间隔着一段**
-- ---------------------------------------------------------------------------
-- 原著 ch67 火弹术、ch74 御风决，中间隔着开炉行医、厉飞雨中毒拔毒一整段。
-- 地图上 trigger_yufeng 没有 guard_flag，所以这一段由脚本自己守：
-- 开头查 ch04.kailu，没开炉就说一句再 return（走不到末尾，once 不烧，回头再来照演）。
-- 不拿火弹术当前置而拿开炉当前置，是因为开炉本身就以火弹术为前置（kailu.lua 开头），
-- 一道闸兜住两道，顺序仍旧是 2 → 3 → 4。
--
-- ---------------------------------------------------------------------------
-- 取材角度：原著写「上瘾」，本作写他**被这份上瘾吓着了**
-- ---------------------------------------------------------------------------
-- ch74 那一段的落点是痛快：身轻如燕，每日要在山谷里狂奔五六遍才罢休。
-- 本作留住了那个次数递增的形状（五趟、六趟、七趟），但把落点换了：
-- 跑完他坐在石栏上问自己「我跑这些做什么」，想不出来 ——
-- 他这十几年做过的每一件事都有个为什么，这是头一件没有的。
-- 一个从十岁起就在算自己能不能活的人，头一次做一件没有理由的事，
-- 这比痛快更像他，也给节点 5 那次「他也说不清为什么没撒手」埋了引信。
--
-- 另加一条原著没有的细节，用来把他钉在自己的性子上：**他量过崖**。
-- 从台面断口往回退十一步做记号，此后只在记号这一侧动。一个要练身法的人先量的是
-- 摔下去的那一边 —— 这是第 2 章那个先数退路的少年。
--
-- 御风决的短处（拐不了急弯）是原著明写的（ch75 与罗烟步对照那一段），
-- 本节先摆出来，节点 5 才有东西可凑。**但那一凑不能在这里发生**：
-- 硬约束 1 说法武并用是他自己摸出来的，这一节结尾只写「两样各管各的，
-- 还没有凑到一块去」。
--
