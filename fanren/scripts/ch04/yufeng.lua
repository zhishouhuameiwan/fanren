-- ---------------------------------------------------------------------------
-- 峰上这一年的俸禄药材（第 4 章复验 N-1 / 技术债 G-12）
-- ---------------------------------------------------------------------------
-- `ch04.kailu.salary` 的原话是「**按月**抬到峰下」，而 kailu.lua 只发了头一个月。
-- 节点 3 到这里隔着上面那 360 天——十二个月的俸禄，在机制上从前从来没有发生过，
-- 于是本章发下来的料连养精丹那道熟练度门槛都垫不够，攻防战要的药一瓶也炼不出，
-- 而通关测试靠无限补料把这件事盖住了。
--
-- 这十二个月是在上面那一句 advance_days 里过去的，玩家在这一年里够不着炉子，
-- 所以按月发与在这里一次发，到手的时刻与数目都一样；写成一次，数目在一处看得见。
-- **两条报价发的一样**：照价与只收药钱分的是头一个月那一份（kailu.lua），
-- 往后按供奉的例，月月一样。年份 24，与照价那一份同，压过养精丹那道 20 年门槛。
--
-- 数目对着 docs/ch04-design.md 3.3 那张炉数表：月例十二个月，每月黄精 6、紫参 3
--（与照价那一条头一个月同数），外加年底按两个月算的年例——合十四个月的份，
-- 黄精 84、紫参 42。加上头一个月，照价那一条共 45 炉的料：按 Crafting.cpp 的公式，
-- 期望炼出 23 瓶，坏情况（5% 分位）16 瓶，而本章要的是 13 瓶（那张表的合计）。
-- tests/Ch04SalaryTests.cpp 的 Ch04Salary 那一组**直接读本文件与 kailu.lua 的 give**，
-- 与设计写死的数比。**这两行必须留在顶层（不缩进）**：那一组把不缩进的 give 当作
-- 无条件发放来记账，挪进 if 里它会报出来。
