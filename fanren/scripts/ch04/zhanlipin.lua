-- @hook ch04_yanwuchang trigger_zhanlipin interact once
-- 第四章节点 10「战利品：剑符与那块牌子」。
-- 挂在 ch04_yanwuchang 校场东头那片焦土上 (36,24)(37,24) 的 trigger
-- （mode=interact，once=true，guard_flag=ch04.gongfang_zhan，set_flag=ch04.pai_dedao）。
-- 焦土是 (33,22)-(39,27) 那一片（genmaps_ch04.py：ground 换成第 3 号特殊地表，
-- overlay 撒碎石），空场里的一处地标，不在任何一条路上 —— 玩家得自己走过去、
-- 面朝它按确认。那是金光上人倒下的地方。
--
-- ===========================================================================
-- **这个脚本最要紧的一条：那块牌子不能有名字。**
-- 改它之前请读 docs/ch04-design.md 第 1.1 节与 data/items/materials/heipai.json 的 note。
-- ===========================================================================
-- 「升仙令」三个字在原著里首见于 ch141，远在本章（ch65-99）之外。ch141 才交代
-- 他很早就得了它、**不知道是什么**，后来听人说起升仙大会也没往一处想，当成巧合
-- 扔到脑后，直到在一本小册子上看见图样，图下写着那三个字。
--
-- 所以本节对它做的每一件事都是减法：
--   · 物品名写成少年看得见的样子 —— 「一块黑牌子」。
--   · 描述只写他看见了什么（三角、磨圆的边、比看着沉、不脆也不是石头、
--     几道绕来绕去的印子看不出是字还是花纹），**一个用途暗示也没有**。
--   · **没有任何 NPC 解释它**，本节也没有一句「日后或有大用」。
--   · 它不是任务物品，不进任务栏。
--   · 他收起它的理由写成了没有理由：「他把它和碎银放在一处。没有什么特别的道理，
--     那个布袋本来就是装零碎的。」
--   · 同一堆灰里还有一本别人家的家谱（原著 ch93），他翻两页就丢回去了。
--     那本册子在这里是有活干的：**它让这一堆看起来就是一堆杂物**。
--
-- 判据（设计文档原话）：一个只看物品栏的玩家，应当把它当成一件没用的杂物。
--
-- ---------------------------------------------------------------------------
-- 剑符正好相反，**这个对比本身就是设计**
-- ---------------------------------------------------------------------------
-- 它有名字，描述直说它是什么、干什么用 —— 因为昨夜那道灰光在他眼前把人划开，
-- 他看得清清楚楚。玩家该知道它是什么。
-- **但他此刻催不动它**，这一层也是原著的（ch92：他自陈驱物术生疏，
-- 不敢当着原主人的面用，就是用上也很难伤得了对方）。所以摊开试的那一条里，
-- 小剑只抬起一指高就落回纸面 —— 他缺的不是力气，是一句话，而那句话不在他手上。
--
-- 原著里他是当场用驱物术把飞剑从半空抹走的；本作没有教他驱物术（这一章他只学了
-- 火弹术与御风决），所以两件东西都是从灰里翻出来的。这一处的改动连同理由
-- 写在 data/items/talismans/jianfu.json 的 note 里。
--
-- ---------------------------------------------------------------------------
-- 二选一：剑符当场试不试（ch04.jianfu_dedao = 1 试了 / 2 收起来没摊开）
-- ---------------------------------------------------------------------------
-- **ch04.jianfu_dedao 必须置在末尾那一行之前**（施工纪律第 1 条：once 的判据
-- 只看 set_flag 指的 ch04.pai_dedao）。两条都拿得到剑符，分的是他知道多少 ——
-- 试过的那一条，他已经知道自己差的是什么；没试的那一条，他要到第 5 章才知道。
--
-- 两件东西都用 give()，不用 take()，所以没有返回值要看；
-- 本节唯一一处「取」是不存在的 —— 灰里的东西不属于任何人。

if flag.get("ch04.pai_dedao") ~= 0 then
    talk("", "ch04.zhanli.again")
    return
end

talk("", "ch04.zhanli.ash")
talk("", "ch04.zhanli.sift")
talk("", "ch04.zhanli.fu")
talk("", "ch04.zhanli.know")

give("talisman_jianfu", 1)

local pick = choice{
    "ch04.zhanli.opt_try",
    "ch04.zhanli.opt_keep",
}

if pick == 2 then
    talk("", "ch04.zhanli.keep1")
    talk("", "ch04.zhanli.keep2")
else
    -- 试一试（pick == 1）与取消（pick == nil）走同一条。
    -- 没做选择按试算：他蹲在灰里，手上是一件亲眼见过威力的东西，
    -- 四下无人 —— 这正是他一贯挑的那种时候。
    talk("", "ch04.zhanli.try1")
    talk("", "ch04.zhanli.try2")
end

flag.set("ch04.jianfu_dedao", pick == 2 and 2 or 1)

-- ---------------------------------------------------------------------------
-- 以下是那块牌子。**这一段以下不许出现任何解释性的台词。**
-- ---------------------------------------------------------------------------
talk("", "ch04.zhanli.book")
talk("", "ch04.zhanli.pai")

give("material_heipai", 1)

talk("", "ch04.zhanli.feel")
talk("", "ch04.zhanli.marks")
talk("", "ch04.zhanli.pocket")
talk("", "ch04.zhanli.end")

flag.set("ch04.pai_dedao")
