-- 厉飞雨的闲聊（第 4 章版本）。挂在 ch04_getang 内院当中 (20,23) 的 npc_li_feiyu 上
-- （role_id=li_feiyu，facing=down，不游走）。他不在任何一条路上 ——
-- 关卡侧是有意这么摆的：玩家愿意找他说话才说得上。
-- npc 对象没有 mode 也没有 once，@hook 只写 npc 一个取值，不许写 once。
--
-- ---------------------------------------------------------------------------
-- 硬约束 2（设计文档第 1 节第 5 条）：**门派存续，厉飞雨活着并接任外刃堂堂主
-- 兼门主关门弟子。** 最后那两条就是这件事的落点，写在明处，不留余地。
-- ---------------------------------------------------------------------------
-- 设计文档第 6 节点名要求：「别把他写成陪衬 —— 他接任堂主是原著明写的，
-- 不是安慰奖。」所以最后两条里他说的是**他自己的难处**：
-- 堂里那些人的命从此压在他手上，压得他夜里睡不实。他不是来道贺的，
-- 也不是来送别的，他是接了一副担子。
-- 韩立听完那一句，心里想的是「这人还活着」—— 全章他对朋友唯一一次直白的情绪，
-- 放在这里，一句就够。
--
-- ---------------------------------------------------------------------------
-- 中间那三条是原著 ch74 那一段谈话的落地，**角度换过**
-- ---------------------------------------------------------------------------
-- 原著里韩立劝他散功、可多活些年，他不肯，理由是「我成了个手无缚鸡之力的庸人，
-- 张姑娘还看得上我吗」。原著那一段是两个人在山路上当面说完的，收在一记
-- 用了内劲的拍肩上。
-- 本作把它拆成三次闲聊（张姑娘家里在问日子 → 韩立劝 → 他笑了半声就停），
-- 因为闲聊是玩家自己走过去点出来的：**劝不劝、听不听得完，由玩家决定**，
-- 而不是由一段过场替他决定。韩立没有再劝第二遍，也没有答他那句反问，
-- 只是「把头转开了」—— 这一句替代了原著里那一整段内心权衡。
-- 那记用了内劲的拍肩挪到了节点 5（qiecuo.lua 的说实话分支），不在这里重复使用。
--
-- 抽髓丸与他的寿数，本章**一个字也不点破**（data/roles/li_feiyu.json 的 note：
-- 本章不得透出其寿数结局）。这几条只说「散了能多活些年头」，不说为什么。
--
-- 分段只用本章已登记的旗标，不另立。五条路都有话说，没有一条静默返回。

