-- 刚看见父母的头发白了。** 信里写什么，是被这一眼决定的。
-- 原著 ch98 里他是先把药和纸条留在厉飞雨屋里再上车回村的；本作把两件事调了个个儿，
-- 信改成托车夫捎回山下（车夫本来就要回去）。这一处改动连同理由写在交付报告里。
--
-- ---------------------------------------------------------------------------
-- 取材角度：原著整整两章（ch98 回村、ch99 离开）的分量，本作收成一节
-- ---------------------------------------------------------------------------
-- 原著里这一段最要命的是「他什么也没做」：躲在树后看完妹妹出嫁，转身走了。
-- 本作一个字也没有替他说 —— 没有内心独白式的道别，没有「我一定会回来」。
-- 两处钉语气的地方：
--   · ch04.huicun.nogo：走出去就得解释这四年 —— 谷里的事、峰上的事、校场上那一夜的事
--     （不写「昨夜」：攻防战与回村之间隔着 advance_days(5)），
--     这些话没有一句说得出口。他不走出去的理由是具体的，不是煽情的。
--   · ch04.huicun.end：人散了他才发现自己一直攥着那个布袋。那个布袋里是碎银，
--     以及节点 10 那块没有名字的黑牌子 —— **这里绝不点破它**，只写手心的汗。
--
-- ---------------------------------------------------------------------------
-- 细节的来路：不照搬车上的东西，改用「他这四年养出来的眼睛」（HIGH-1 整改）
-- ---------------------------------------------------------------------------
-- 初版这一节的细节是顺着原著那张清单排下来的（篷车、车夫、鸟、包裹、矮泥墙、
-- 稻草垛、村妇八卦、三叔胖大哥黑、白发双亲、彩车青马），种类、数量、顺序三样
-- 都对得上，按设计文档第 6 节的判据那仍算转写。现改为：
--   · **删掉**车上那两条（ch04.huicun.bird 整条删；gossip 整条删）。他带的东西
--     由 ch04.dongqu.bag 一条交代完，不在这里重复铺陈。
--   · 这一场只让他看见**药人看得见的东西**：空村子先想到疫病（music）、
--     先把人数一遍（home，与节点 8 ch04.jinguang.herb 同一双眼睛）、
--     红纸的浆糊干没干、碗是不是各家凑的（red）、母亲指关节的肿（parents）、
